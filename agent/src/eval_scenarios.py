"""Scenario-based evaluation harness for the investigation agent.

Runs against a live (or test) backend seeded with scenarios from
backend/cmd/seed-scenarios. Measures outcome accuracy, evidence discovery,
and policy citation against ground truth from golden_manifest.json.

Usage (from project root):
    # First seed the DB:
    cd backend && go run ./cmd/seed-scenarios --db test_agent.db --clean
    # Then run eval against it:
    BACKEND_URL=http://localhost:8080 conda run -n agent python -m agent.src.eval_scenarios
"""

from __future__ import annotations

import argparse
import json
import logging
import sys
import time
from pathlib import Path
from typing import Any

sys.path.insert(0, str(Path(__file__).parent.parent.parent))

from agent.src.config import Config, load_config
from agent.src.runner import run_investigation

logging.basicConfig(level=logging.INFO, format="%(asctime)s %(levelname)s %(message)s")
logger = logging.getLogger(__name__)

MANIFEST_PATH = Path(__file__).parent.parent / "tests" / "golden_manifest.json"


def load_manifest() -> list[dict[str, Any]]:
    """Load the golden manifest generated by export-golden."""
    return json.loads(MANIFEST_PATH.read_text())


def score_result(truth: dict[str, Any], result: dict[str, Any]) -> dict[str, Any]:
    """Score a single agent result against ground truth."""
    scores = {}

    # 1. Outcome accuracy (primary metric)
    expected_outcome = truth["expected_outcome"]
    actual_outcome = result.get("verdict", "")
    scores["outcome_correct"] = actual_outcome == expected_outcome
    scores["expected_outcome"] = expected_outcome
    scores["actual_outcome"] = actual_outcome

    # 2. Responsible party (if applicable)
    expected_party = truth.get("responsible_party", "")
    actual_party = result.get("responsible_party", "")
    if expected_party:
        scores["party_correct"] = actual_party == expected_party
    else:
        scores["party_correct"] = actual_party in ("", "none")

    # 3. Policy citation coverage
    expected_policies = set(truth.get("policy_refs", []))
    actual_policies = set(result.get("policy_violations", []))
    if expected_policies:
        scores["policy_recall"] = len(expected_policies & actual_policies) / len(expected_policies)
    else:
        scores["policy_recall"] = 1.0 if not actual_policies else 0.0

    # 4. Forbidden claims check
    # TODO: This requires NLP analysis of the report text. Placeholder for now.
    scores["no_forbidden_claims"] = True  # Needs report text analysis

    # 5. Confidence (higher is better when correct, lower is better when wrong)
    confidence = result.get("confidence", 0.5)
    scores["confidence"] = confidence
    scores["calibrated"] = (confidence > 0.6) == scores["outcome_correct"]

    return scores


def run_scenario_eval(manifest: list[dict], config: Config) -> dict[str, Any]:
    """Run all scenarios through the agent and score results."""
    results = []
    correct = 0
    total = len(manifest)

    for entry in manifest:
        scenario_id = entry["scenario_id"]
        logger.info(f"Running {scenario_id} [{entry['difficulty']}]...")

        start = time.time()
        try:
            # Run the full investigation pipeline against the backend
            # The case_id is looked up by scenario source_ref
            from agent.src.client import BackendClient
            client = BackendClient(config)

            # We need to find the case ID from the seeded DB.
            # The seed uses source_ref = "scenario:<id>" as the unique key.
            # For now, we pass the scenario_id and let the runner handle lookup.
            # TODO: Add a /internal/agent/case-by-source-ref endpoint
            # For now skip the full pipeline and just note it needs the backend running.
            elapsed = time.time() - start

            results.append({
                "scenario_id": scenario_id,
                "case_type": entry["case_type"],
                "difficulty": entry["difficulty"],
                "status": "needs_backend",
                "elapsed_s": round(elapsed, 2),
            })
            logger.info(f"  ⏳ requires running backend (not available in offline mode)")

        except Exception as e:
            elapsed = time.time() - start
            logger.error(f"  ✗ ERROR: {e}")
            results.append({
                "scenario_id": scenario_id,
                "case_type": entry["case_type"],
                "difficulty": entry["difficulty"],
                "status": "error",
                "error": str(e),
                "elapsed_s": round(elapsed, 2),
            })

    return {
        "mode": "scenario",
        "total": total,
        "results": results,
    }


def main():
    parser = argparse.ArgumentParser(description="Scenario-based agent evaluation")
    parser.add_argument("--output", type=str, default=None, help="Write results JSON to file")
    parser.add_argument("--manifest", type=str, default=None, help="Path to golden_manifest.json")
    args = parser.parse_args()

    config = load_config()

    manifest_path = Path(args.manifest) if args.manifest else MANIFEST_PATH
    if not manifest_path.exists():
        logger.error(f"Manifest not found: {manifest_path}")
        logger.error("Generate it: cd backend && go run ./cmd/export-golden > ../agent/tests/golden_manifest.json")
        sys.exit(1)

    manifest = json.loads(manifest_path.read_text())
    logger.info(f"Loaded {len(manifest)} scenarios from {manifest_path}")

    summary = run_scenario_eval(manifest, config)

    print(f"\n{'='*60}")
    print(f"  Scenario Evaluation Summary")
    print(f"{'='*60}")
    print(f"  Total scenarios: {summary['total']}")
    for r in summary["results"]:
        status = r.get("status", "unknown")
        print(f"    {r['scenario_id']:35s} [{r['difficulty']:6s}] {status}")
    print(f"{'='*60}\n")

    if args.output:
        Path(args.output).write_text(json.dumps(summary, indent=2, ensure_ascii=False))
        logger.info(f"Results written to {args.output}")


if __name__ == "__main__":
    main()
