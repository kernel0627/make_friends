"""Scenario-based evaluation harness for the investigation agent.

End-to-end flow:
  1. Seeds test DB via go run ./cmd/seed-scenarios
  2. Starts the Go backend against the test DB
  3. Runs the agent (LLM graph) against each seeded case
  4. Scores agent output against ground truth from golden_manifest.json

Usage (from project root):
    conda run -n agent python -m agent.src.eval_scenarios
    conda run -n agent python -m agent.src.eval_scenarios --scenario content_commercial_01
"""

from __future__ import annotations

import argparse
import json
import logging
import os
import signal
import subprocess
import sys
import time
from pathlib import Path
from typing import Any

sys.path.insert(0, str(Path(__file__).parent.parent.parent))

from agent.src.config import Config, load_config
from agent.src.runner import run_investigation

logging.basicConfig(level=logging.INFO, format="%(asctime)s %(levelname)s %(message)s")
logger = logging.getLogger(__name__)

PROJECT_ROOT = Path(__file__).parent.parent.parent
BACKEND_DIR = PROJECT_ROOT / "backend"
MANIFEST_PATH = PROJECT_ROOT / "agent" / "tests" / "golden_manifest.json"
TEST_DB_PATH = BACKEND_DIR / "test_agent.db"
POLICY_DIR = PROJECT_ROOT / "agent" / "policies"


def load_manifest(path: Path | None = None) -> list[dict[str, Any]]:
    """Load the golden manifest generated by export-golden."""
    p = path or MANIFEST_PATH
    return json.loads(p.read_text())


def seed_database() -> bool:
    """Seed the test database using the Go seed command."""
    logger.info("Seeding test database...")
    result = subprocess.run(
        ["go", "run", "./cmd/seed-scenarios", "--db", str(TEST_DB_PATH), "--clean"],
        cwd=str(BACKEND_DIR),
        capture_output=True, text=True,
    )
    if result.returncode != 0:
        logger.error(f"Seed failed: {result.stderr}")
        return False
    logger.info(result.stdout.strip())
    return True


def start_backend(port: int = 19876, secret: str = "test-agent-secret") -> subprocess.Popen | None:
    """Start the Go backend against the test DB."""
    env = {
        **os.environ,
        "DATABASE_PATH": str(TEST_DB_PATH),
        "AGENT_API_SECRET": secret,
        "AGENT_POLICY_DIR": str(POLICY_DIR),
        "BACKEND_ADDR": f":{port}",
        "GIN_MODE": "release",
    }
    logger.info(f"Starting backend on port {port}...")
    proc = subprocess.Popen(
        ["go", "run", "./cmd/server"],
        cwd=str(BACKEND_DIR),
        env=env,
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
    )
    # Wait for backend to be ready
    import httpx
    for i in range(30):
        time.sleep(0.5)
        try:
            r = httpx.get(f"http://localhost:{port}/healthz", timeout=2)
            if r.status_code == 200:
                logger.info("Backend ready.")
                return proc
        except Exception:
            pass
    logger.error("Backend failed to start within 15s")
    proc.kill()
    return None


def stop_backend(proc: subprocess.Popen):
    """Stop the backend process."""
    if proc and proc.poll() is None:
        proc.send_signal(signal.SIGTERM)
        try:
            proc.wait(timeout=5)
        except subprocess.TimeoutExpired:
            proc.kill()


def score_result(truth: dict[str, Any], result: dict[str, Any]) -> dict[str, Any]:
    """Score a single agent result against ground truth.

    Metrics:
      - outcome_correct: exact verdict match
      - party_correct: responsible party match
      - policy_recall: fraction of expected policy refs cited
      - evidence_recall: fraction of required_evidence found in the agent's report/evidence
      - fabrication_free: no forbidden_claims appear in the agent's output
      - calibrated: confidence > 0.6 iff outcome is correct
    """
    scores = {}

    # 1. Outcome accuracy (primary metric)
    expected_outcome = truth["expected_outcome"]
    actual_outcome = result.get("verdict", "")
    scores["outcome_correct"] = actual_outcome == expected_outcome
    scores["expected_outcome"] = expected_outcome
    scores["actual_outcome"] = actual_outcome

    # 2. Responsible party
    expected_party = truth.get("responsible_party", "")
    actual_party = result.get("responsible_party", "")
    if expected_party:
        scores["party_correct"] = actual_party == expected_party
    else:
        scores["party_correct"] = actual_party in ("", "none", None)

    # 3. Policy citation recall
    expected_policies = set(truth.get("policy_refs", []))
    actual_policies = set(result.get("policy_violations", []) or [])
    if expected_policies:
        scores["policy_recall"] = len(expected_policies & actual_policies) / len(expected_policies)
    else:
        scores["policy_recall"] = 1.0 if not actual_policies else 0.0

    # 4. Evidence recall — check if required evidence types appear in the agent's output
    required_evidence = truth.get("required_evidence", [])
    if required_evidence:
        # Build a searchable text corpus from the agent's report + evidence list
        corpus = _build_evidence_corpus(result)
        found = sum(1 for e in required_evidence if _evidence_mentioned(e, corpus))
        scores["evidence_recall"] = found / len(required_evidence)
        scores["evidence_found"] = found
        scores["evidence_required"] = len(required_evidence)
    else:
        scores["evidence_recall"] = 1.0
        scores["evidence_found"] = 0
        scores["evidence_required"] = 0

    # 5. Fabrication check — forbidden claims must NOT appear in agent output
    forbidden_claims = truth.get("forbidden_claims", [])
    if forbidden_claims:
        corpus = _build_evidence_corpus(result)
        violations = [claim for claim in forbidden_claims if _claim_present(claim, corpus)]
        scores["fabrication_free"] = len(violations) == 0
        scores["fabrication_violations"] = violations
    else:
        scores["fabrication_free"] = True
        scores["fabrication_violations"] = []

    # 6. Confidence calibration
    confidence = result.get("confidence", 0.5)
    scores["confidence"] = confidence
    scores["calibrated"] = (confidence > 0.6) == scores["outcome_correct"]

    return scores


def _build_evidence_corpus(result: dict[str, Any]) -> str:
    """Build a text corpus from the agent's output for evidence/claim searches."""
    parts = []
    if result.get("report"):
        parts.append(result["report"])
    # Evidence list from steps
    for step in result.get("steps", []):
        if step.get("output"):
            parts.append(str(step["output"]))
        if step.get("reasoning"):
            parts.append(step["reasoning"])
    # Policy violations cited
    for p in result.get("policy_violations", []) or []:
        parts.append(p)
    return "\n".join(parts).lower()


def _evidence_mentioned(evidence_key: str, corpus: str) -> bool:
    """Check if an evidence type/key is referenced in the corpus.

    Uses relaxed matching: underscores → spaces, checks for substring.
    """
    # Normalize: "chat_commercial_link" → "commercial link", "chat commercial link"
    normalized = evidence_key.lower().replace("_", " ")
    if normalized in corpus:
        return True
    # Also try underscore form
    if evidence_key.lower() in corpus:
        return True
    # Try individual significant words (length > 3)
    words = [w for w in normalized.split() if len(w) > 3]
    if words and all(w in corpus for w in words):
        return True
    return False


def _claim_present(claim: str, corpus: str) -> bool:
    """Check if a forbidden claim appears in the corpus."""
    normalized = claim.lower().replace("_", " ")
    if normalized in corpus:
        return True
    if claim.lower() in corpus:
        return True
    return False


def find_case_id(client, scenario_id: str) -> str | None:
    """Find case ID by scenario source_ref."""
    cases = client.list_cases(source_ref=f"scenario:{scenario_id}")
    if cases:
        return cases[0]["id"]
    return None


def run_single_scenario(scenario_id: str, truth: dict[str, Any], config: Config) -> dict[str, Any]:
    """Run a single scenario through the agent and return scored result."""
    from agent.src.client import BackendClient

    client = BackendClient(config)
    try:
        case_id = find_case_id(client, scenario_id)
        if not case_id:
            return {"status": "error", "error": f"Case not found for scenario {scenario_id}"}
    finally:
        client.close()

    start = time.time()
    try:
        final_state = run_investigation(case_id, config=config, use_llm=True)
        elapsed = time.time() - start

        if "error" in final_state and final_state.get("error"):
            return {
                "status": "error",
                "error": final_state["error"],
                "elapsed_s": round(elapsed, 2),
            }

        scores = score_result(truth, final_state)
        return {
            "status": "completed",
            "case_id": case_id,
            "elapsed_s": round(elapsed, 2),
            "verdict": final_state.get("verdict", ""),
            "confidence": final_state.get("confidence", 0.0),
            "responsible_party": final_state.get("responsible_party", ""),
            "policy_violations": final_state.get("policy_violations", []),
            "step_count": final_state.get("step_count", 0),
            "scores": scores,
        }
    except Exception as e:
        elapsed = time.time() - start
        logger.exception(f"Error running {scenario_id}")
        return {"status": "error", "error": str(e), "elapsed_s": round(elapsed, 2)}


def run_eval(manifest: list[dict], config: Config, scenario_filter: str = "") -> dict[str, Any]:
    """Run evaluation across scenarios."""
    results = []
    correct = 0
    total = 0

    for entry in manifest:
        scenario_id = entry["scenario_id"]
        if scenario_filter and scenario_id != scenario_filter:
            continue
        total += 1

        logger.info(f"{'='*50}")
        logger.info(f"Running: {scenario_id} [{entry['difficulty']}]")
        logger.info(f"  Expected: {entry['expected_outcome']}")

        result = run_single_scenario(scenario_id, entry, config)
        result["scenario_id"] = scenario_id
        result["case_type"] = entry["case_type"]
        result["difficulty"] = entry["difficulty"]

        if result["status"] == "completed":
            is_correct = result["scores"]["outcome_correct"]
            if is_correct:
                correct += 1
            mark = "✓" if is_correct else "✗"
            logger.info(f"  {mark} verdict={result['verdict']} conf={result['confidence']:.0%} "
                       f"steps={result['step_count']} ({result['elapsed_s']:.1f}s)")
        else:
            logger.error(f"  ✗ {result.get('error', 'unknown error')}")

        results.append(result)

    accuracy = correct / total if total > 0 else 0.0

    # Breakdown
    by_type: dict[str, dict] = {}
    by_diff: dict[str, dict] = {}
    for r in results:
        if r["status"] != "completed":
            continue
        for group, key in [(by_type, r["case_type"]), (by_diff, r["difficulty"])]:
            if key not in group:
                group[key] = {"total": 0, "correct": 0}
            group[key]["total"] += 1
            if r["scores"]["outcome_correct"]:
                group[key]["correct"] += 1

    # Aggregate new metrics
    completed_results = [r for r in results if r["status"] == "completed"]
    avg_evidence_recall = 0.0
    fabrication_clean = 0
    avg_policy_recall = 0.0
    party_correct_count = 0
    calibrated_count = 0

    for r in completed_results:
        s = r["scores"]
        avg_evidence_recall += s.get("evidence_recall", 0.0)
        avg_policy_recall += s.get("policy_recall", 0.0)
        if s.get("fabrication_free", True):
            fabrication_clean += 1
        if s.get("party_correct", False):
            party_correct_count += 1
        if s.get("calibrated", False):
            calibrated_count += 1

    n = len(completed_results) or 1
    avg_evidence_recall /= n
    avg_policy_recall /= n

    return {
        "total": total,
        "completed": len(completed_results),
        "correct": correct,
        "accuracy": round(accuracy, 3),
        "evidence_recall": round(avg_evidence_recall, 3),
        "fabrication_clean_rate": round(fabrication_clean / n, 3),
        "policy_recall": round(avg_policy_recall, 3),
        "party_accuracy": round(party_correct_count / n, 3),
        "calibration_rate": round(calibrated_count / n, 3),
        "by_type": {k: round(v["correct"] / v["total"], 3) for k, v in by_type.items() if v["total"]},
        "by_difficulty": {k: round(v["correct"] / v["total"], 3) for k, v in by_diff.items() if v["total"]},
        "results": results,
    }


def main():
    parser = argparse.ArgumentParser(description="End-to-end scenario agent evaluation")
    parser.add_argument("--scenario", type=str, default="", help="Run a single scenario by ID")
    parser.add_argument("--output", type=str, default=None, help="Write results JSON to file")
    parser.add_argument("--manifest", type=str, default=None, help="Path to golden_manifest.json")
    parser.add_argument("--no-seed", action="store_true", help="Skip DB seeding (assume already seeded)")
    parser.add_argument("--no-backend", action="store_true",
                       help="Skip starting backend (assume already running)")
    parser.add_argument("--port", type=int, default=19876, help="Backend port for test server")
    parser.add_argument("--secret", type=str, default="test-agent-secret", help="Agent API secret")
    args = parser.parse_args()

    # Load manifest
    manifest_path = Path(args.manifest) if args.manifest else MANIFEST_PATH
    if not manifest_path.exists():
        logger.error(f"Manifest not found: {manifest_path}")
        logger.error("Generate: cd backend && go run ./cmd/export-golden > ../agent/tests/golden_manifest.json")
        sys.exit(1)
    manifest = load_manifest(manifest_path)
    logger.info(f"Loaded {len(manifest)} scenarios")

    # Seed DB
    if not args.no_seed:
        if not seed_database():
            sys.exit(1)

    # Start backend
    backend_proc = None
    if not args.no_backend:
        backend_proc = start_backend(port=args.port, secret=args.secret)
        if not backend_proc:
            sys.exit(1)

    try:
        # Set env vars so load_config() picks up test backend
        os.environ["AGENT_BACKEND_URL"] = f"http://localhost:{args.port}"
        os.environ["AGENT_API_SECRET"] = args.secret

        config = load_config()

        # Run eval
        summary = run_eval(manifest, config, scenario_filter=args.scenario)

        # Print summary
        print(f"\n{'='*60}")
        print(f"  Scenario Evaluation Results")
        print(f"{'='*60}")
        print(f"  Completed: {summary['completed']}/{summary['total']}")
        print(f"  Accuracy:  {summary['correct']}/{summary['completed']} ({summary['accuracy']:.1%})")
        print(f"\n  Extended metrics:")
        print(f"    Evidence recall:    {summary['evidence_recall']:.1%}")
        print(f"    Fabrication-free:   {summary['fabrication_clean_rate']:.1%}")
        print(f"    Policy recall:      {summary['policy_recall']:.1%}")
        print(f"    Party accuracy:     {summary['party_accuracy']:.1%}")
        print(f"    Calibration:        {summary['calibration_rate']:.1%}")
        if summary["by_type"]:
            print(f"\n  By case type:")
            for t, acc in summary["by_type"].items():
                print(f"    {t:25s} {acc:.1%}")
        if summary["by_difficulty"]:
            print(f"\n  By difficulty:")
            for d, acc in summary["by_difficulty"].items():
                print(f"    {d:10s} {acc:.1%}")
        print(f"{'='*60}\n")

        if args.output:
            Path(args.output).write_text(json.dumps(summary, indent=2, ensure_ascii=False))
            logger.info(f"Results written to {args.output}")

    finally:
        if backend_proc:
            stop_backend(backend_proc)
            logger.info("Backend stopped.")


if __name__ == "__main__":
    main()